#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(fs.readFileSync(path.join(root, "sources/catalog.json"), "utf8"));
const checkOnly = process.argv.includes("--check");

function read(relativePath) {
  return fs.readFileSync(path.resolve(root, relativePath), "utf8").replace(/\r\n/g, "\n").trim();
}

function stripFrontmatter(markdown) {
  return markdown.replace(/^---\n[\s\S]*?\n---\n+/, "").trim();
}

function demoteHeadings(markdown, amount = 1) {
  return markdown.replace(/^(#{1,5})(?=\s)/gm, (heading) => "#".repeat(amount) + heading);
}

function buildProjectBrain() {
  const sections = catalog.projectBrain.map((source) => {
    const body = demoteHeadings(stripFrontmatter(read(source)));
    return `<!-- source: ${source} -->\n\n${body}`;
  });

  return [
    "# GridPool Project Brain",
    "",
    "> Generated from the modular GridPool handbook. Do not edit this file directly.",
    "> Claims retain the status and evidence boundaries described in Source Of Truth.",
    "",
    ...sections
  ].join("\n\n") + "\n";
}

function buildFullCorpus(projectBrain) {
  const sections = catalog.corpus.map((source) => {
    const absolutePath = path.resolve(root, source.path);
    if (!fs.existsSync(absolutePath)) {
      throw new Error(`Missing corpus source: ${source.path}`);
    }
    const body = demoteHeadings(stripFrontmatter(read(source.path)), 1);
    return [
      `## Corpus Source: ${source.title}`,
      "",
      `- Repository: \`${source.repository}\``,
      `- Pinned revision: \`${source.revision}\``,
      `- Canonical source: ${source.canonicalUrl}`,
      "",
      body
    ].join("\n");
  });

  return [
    "# GridPool Full Agent Corpus",
    "",
    "> Generated context bundle. The source repositories remain canonical.",
    "> Embedded documents are pinned snapshots and may be historical after their listed revision.",
    "",
    projectBrain.replace(/^# GridPool Project Brain\n+/, "## Curated Project Brain\n\n"),
    "",
    "## Embedded Canonical And Evidence Documents",
    "",
    ...sections
  ].join("\n\n") + "\n";
}

function writeOrCheck(relativePath, content) {
  const absolutePath = path.join(root, relativePath);
  if (checkOnly) {
    const current = fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, "utf8") : "";
    if (current !== content) {
      throw new Error(`${relativePath} is stale; run node scripts/build-project-brain.mjs`);
    }
    return;
  }
  fs.writeFileSync(absolutePath, content);
}

const projectBrain = buildProjectBrain();
writeOrCheck("GRIDPOOL-PROJECT-BRAIN.md", projectBrain);
writeOrCheck("GRIDPOOL-FULL-CORPUS.md", buildFullCorpus(projectBrain));
console.log(checkOnly ? "Generated bundles are current." : "Generated GridPool context bundles.");
